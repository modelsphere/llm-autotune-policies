// Third-party notices for what the image ships, and a gate against copyleft.
//
// Walks the production dependency tree (npm ls --omit=dev), writes every
// package's name, version, license and license text to THIRD_PARTY_LICENSES,
// and exits non-zero if any license is copyleft. The image carries the file;
// CI runs this on every change.

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const COPYLEFT = /\b(A?GPL|LGPL|SSPL|EUPL|OSL|CC-BY-SA)\b/i;

const parseable = execFileSync("npm", ["ls", "--omit=dev", "--all", "--parseable"], { encoding: "utf8" });
const dirs = [...new Set(parseable.split("\n").map((l) => l.trim()).filter(Boolean))].slice(1); // first line is this package

const entries = [];
const problems = [];
for (const dir of dirs) {
  const pkgPath = join(dir, "package.json");
  if (!existsSync(pkgPath)) continue;
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(" OR ") ?? "";
  if (!license) problems.push(`${pkg.name}@${pkg.version}: no license declared`);
  // "(MIT OR GPL-3.0)" lets us pick MIT; only refuse when no permissive choice exists.
  const choices = license.replace(/[()]/g, "").split(/\s+OR\s+/i);
  if (choices.length && choices.every((c) => COPYLEFT.test(c))) problems.push(`${pkg.name}@${pkg.version}: copyleft license ${license}`);
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(f));
  const text = file ? readFileSync(join(dir, file), "utf8").trim() : `(no license file shipped; declared: ${license})`;
  entries.push({ name: pkg.name, version: pkg.version, license, text });
}

entries.sort((a, b) => a.name.localeCompare(b.name));
const body = [
  "Third-party software shipped in the llm-autotune agent policy image.",
  `Generated by scripts/licenses.mjs from the production dependency tree (${entries.length} packages).`,
  "",
  ...entries.flatMap((e) => ["=".repeat(78), `${e.name}@${e.version} — ${e.license}`, "=".repeat(78), e.text, ""]),
].join("\n");
writeFileSync("THIRD_PARTY_LICENSES", body);

const summary = new Map();
for (const e of entries) summary.set(e.license, (summary.get(e.license) ?? 0) + 1);
console.log(`${entries.length} production packages:`, Object.fromEntries(summary));
if (problems.length) {
  for (const p of problems) console.error(`license problem: ${p}`);
  process.exit(1);
}
